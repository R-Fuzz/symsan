#!/usr/bin/env bash
# ucsan_abilist.sh LIBCXX_A OUT
#
# UCSan's abilist for the taint-instrumented libc++ (ucsan_opt --libcxx):
# every function libc++.a defines an instrumented copy of (`X.taint`) is
# `uninstrumented` to UCSanPass, which then leaves its calls to TaintPass
# (calling X.taint) instead of a symbolic stub.  ucsan_abilist.txt's custom
# entries (__next_prime, operator new) are matched first and keep theirs.
# Its data (vtables, VTTs, typeinfo, the standard streams) is listed
# `global:`, which UCSanPass then leaves undefined for libc++.a to define,
# instead of a zero weak definition of its own.
set -euo pipefail
NM=$(command -v llvm-nm-18 || command -v llvm-nm || command -v nm)
{
  echo "# generated by libcxx/ucsan_abilist.sh from $(basename "$1")"
  "$NM" --defined-only "$1" 2>/dev/null |
    awk '($2 == "T" || $2 == "W") && $3 ~ /\.taint$/ {
           sub(/\.taint$/, "", $3); print "fun:" $3 "=uninstrumented" }
         $2 ~ /^[VDRB]$/ && $3 !~ /\.taint$/ {
           print "global:" $3 "=uninstrumented" }' |
    sort -u
} > "$2"
